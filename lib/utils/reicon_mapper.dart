import 'package:flutter/material.dart';
import 'package:reicon_flutter/reicon_flutter.dart';

/// Maps a Material [IconData] to a Reicon icon name and style.
class ReiconSpec {
  final String name;
  final bool filled;

  const ReiconSpec(this.name, {this.filled = false});

  @override
  bool operator ==(Object other) =>
      other is ReiconSpec && other.name == name && other.filled == filled;

  @override
  int get hashCode => Object.hash(name, filled);
}

