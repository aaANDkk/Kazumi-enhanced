  ReiconMapper._();

  static final Map<ReiconSpec, String> _svgCache = <ReiconSpec, String>{};
  static final Map<IconData, ReiconSpec> _iconMap =
      Map<IconData, ReiconSpec>.unmodifiable(Map.fromEntries(_entries));

  /// All registered Material [IconData] to [ReiconSpec] entries.
  static List<MapEntry<IconData, ReiconSpec>> get entries => _entries;

  /// Returns the [ReiconSpec] mapped to [icon], or null if unmapped.
  static ReiconSpec? resolveSpec(IconData? icon) =>
      icon == null ? null : _iconMap[icon];

  /// Returns the SVG markup mapped to [icon], or null if unmapped.
  /// Optional [filled] overrides the entry's default fill style.
  static String? resolveSvg(IconData? icon, {bool? filled}) {
    final spec = resolveSpec(icon);
    if (spec == null) return null;
    return resolveSvgByName(spec.name, filled: filled ?? spec.filled);
  }

  /// Returns the SVG markup for a named Reicon glyph, cached in memory.
  static String? resolveSvgByName(String name, {bool filled = false}) {
    final spec = ReiconSpec(name, filled: filled);
    final cached = _svgCache[spec];
    if (cached != null) return cached;
    final pathData = filled ? Reicon.filled[name] : Reicon.outline[name];
    if (pathData == null) return null;
    final svg = reiconSvg(pathData);
    _svgCache[spec] = svg;
    return svg;
  }

